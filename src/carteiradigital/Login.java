    /**
     * botão para fazer login na wallet
     * @param evt 
     */
    private void btLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btLoginActionPerformed
        try {
            String name = txtLoginName.getText().trim();
            String pass = new String(txtPasword.getPassword());

        // O administrador faz login com as credenciais "admin/admin".
        // Internamente estas credenciais são convertidas para o utilizador
        // especial "SYSTEM", evitando alterações na lógica da aplicação
        // e mantendo a compatibilidade com a blockchain.
            if (name.equalsIgnoreCase("admin")) {
                name = "SYSTEM";
            }
            User user = new User(name, pass);
                this.dispose();
            new DigitalWalletGui(user).setVisible(true);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Credenciais erradas", "login", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }


    }//GEN-LAST:event_btLoginActionPerformed
    /**
     * botão para criar conta utilizando os campos do nome e password
     * @param evt 
     */
    private void btRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btRegisterActionPerformed
        //regista e nao deixa registar só com espaços
        String name = txtregisterName.getText().trim();
        File priv = new File(name + ".priv");
        File pub = new File(name + ".pub");
        //validações
        if (priv.exists() || pub.exists()) {
            JOptionPane.showMessageDialog(this, "Esse utilizador já existe!");
            return;
        }
        if ("".equals(name)) {
            JOptionPane.showMessageDialog(this, "Introduza um nome");
            return;
        }
        String pass1 = new String(txtRegisterPass1.getPassword());
        if ("".equals(pass1)) {
            JOptionPane.showMessageDialog(this, "Introduza uma password");
            return;
        }
        String passConf = new String(txtRegisterPass2.getPassword());
        if ("".equals(passConf)) {
            JOptionPane.showMessageDialog(this, "Introduza uma password");
            return;
        }
        if (!pass1.equals(passConf)) {
            JOptionPane.showMessageDialog(this, "As password não são iguais", "Erro!", JOptionPane.ERROR_MESSAGE);
            txtRegisterPass1.setText("");
            txtRegisterPass2.setText("");
            return;
        }
        //registo do utilizador
        User.register(name, passConf);
        JOptionPane.showMessageDialog(this, "Utilizador criado com sucesso!");
        txtregisterName.setText("");
        txtRegisterPass1.setText("");
        txtRegisterPass2.setText("");


    }//GEN-LAST:event_btRegisterActionPerformed
